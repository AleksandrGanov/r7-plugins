/**
 * Исполнитель кода команд Р7-Офис.
 * Вызывается плагином внутри callCommand и работает в контексте документа:
 * объект Api (Builder API) доступен напрямую.
 * Единственная задача — исполнить переданный код команды и вернуть статус.
 * Никаких команд в файле нет: код приходит готовым от Алисы (из библиотеки
 * команд проекта или сформированный заново). Корректность кода не проверяется —
 * её проверяет сам документ при исполнении.
 * Данные берёт из параметра code (строка с кодом Builder API),
 * отдаёт объект результата {ok: true, info: "..."} либо {ok: false, error: "..."}.
 */
function R7Executor(code) {
    if (typeof code !== "string" || !code.trim())
        return { ok: false, error: "пустой код команды" };

    try {
        // Исполняем готовый код команды в контексте документа
        var result = eval(code);

        // Если команда вернула значение — включаем его в отчёт плагину
        var info = (result !== undefined) ? "команда исполнена: " + String(result) : "команда исполнена";

        return { ok: true, info: info };
    } catch (e) {
        // Текст ошибки формирует сам документ — передаём его как есть
        return { ok: false, error: String(e && e.message ? e.message : e) };
    }
}

